//go:build !js

// This offline fixture bakes a small static area light over the sample floor.
package bake

import (
	"crypto/sha256"
	"encoding/binary"
	"math"

	"github.com/karty-game/ashura/internal/meshdata"
	"github.com/karty-game/ashura/internal/modeldata"
	"github.com/karty-game/ashura/internal/render"
	"github.com/karty-game/ashura/pkg/assetbuild"
	"github.com/karty-game/ashura/samples/luminous/internal/courtyard"
)

// Floor publishes a prepared receiver mesh, UV1 and linear static irradiance.
type Floor struct{}

func (Floor) Name() string { return "luminous-floor" }

const floorCatalog = `// Code generated by the Luminous floor bake. DO NOT EDIT.

package assets

import _ "embed"

//go:embed floor.kmodel
var floorModel []byte

//go:embed floor.uv
var floorUV []byte

//go:embed floor-light.rgba
var floorLight []byte

// BakedFloor returns the prepared mesh, UV layout and linear irradiance.
func BakedFloor() (model, uv, irradiance []byte) { return floorModel, floorUV, floorLight }
`

func (floor Floor) Plan(plan *assetbuild.Plan) error {
	const slot = "prepared-floor"

	refs, err := plan.Add(assetbuild.Action{
		ID: floor.Name(), Processor: floor.Name(), Revision: "4",
		Outputs: []assetbuild.Slot{{Name: slot, Schema: "luminous-floor-bundle@1"}},
		Run: func(*assetbuild.Context) (assetbuild.Result, error) {
			files, err := bake()
			if err != nil {
				return nil, err
			}

			data, err := assetbuild.EncodeBundle(files)
			if err != nil {
				return nil, err
			}

			return assetbuild.Result{slot: data}, nil
		},
	})
	if err != nil {
		return err
	}

	plan.Publish(refs[0])

	return nil
}

//nolint:mnd // The quad and its material define the authored baked floor.
func bake() (assetbuild.Bundle, error) {
	vertices := []render.Vertex{
		{Position: [3]float32{-courtyard.HalfWidth, 0, -courtyard.HalfDepth}, Normal: [3]float32{0, 1, 0}, UV: [2]float32{0, 0}},
		{Position: [3]float32{courtyard.HalfWidth, 0, -courtyard.HalfDepth}, Normal: [3]float32{0, 1, 0}, UV: [2]float32{1, 0}},
		{Position: [3]float32{courtyard.HalfWidth, 0, courtyard.HalfDepth}, Normal: [3]float32{0, 1, 0}, UV: [2]float32{1, 1}},
		{Position: [3]float32{-courtyard.HalfWidth, 0, courtyard.HalfDepth}, Normal: [3]float32{0, 1, 0}, UV: [2]float32{0, 1}},
	}

	payload, err := modeldata.EncodeWithBounds(modeldata.Document{Source: "Luminous floor", Parts: []modeldata.Part{{
		Name: "floor", Vertices: render.AppendVertices(nil, vertices), Indices: render.AppendIndices(nil, []uint32{0, 2, 1, 0, 3, 2}),
		Bounds: meshdata.Bounds{Minimum: vertices[0].Position, Maximum: vertices[2].Position, Valid: true},
		Material: modeldata.Material{
			Color:     [4]float32{courtyard.FloorRed, courtyard.FloorGreen, courtyard.FloorBlue, 1},
			Roughness: .72, Albedo: -1, Normal: -1, AO: -1,
		},
	}}})
	if err != nil {
		return nil, err
	}

	digest := sha256.Sum256(payload)
	layoutUV := digest[:]

	for _, vertex := range vertices {
		for _, value := range vertex.UV {
			layoutUV = binary.LittleEndian.AppendUint32(layoutUV, math.Float32bits(value))
		}
	}

	return assetbuild.Bundle{
		"floor.go":         []byte(floorCatalog),
		"floor.kmodel":     payload,
		"floor.uv":         layoutUV,
		"floor-light.rgba": bakeFloor(),
	}, nil
}

//nolint:mnd // The bake uses fixed texel centers, linear irradiance and a small authored area light.
func bakeFloor() []byte {
	const (
		resolution   = courtyard.BakeResolution
		samples      = 16
		emitterWidth = 1.8
		emitterStep  = emitterWidth / samples
	)

	pixels := make([]byte, resolution*resolution*4)
	for row := range resolution {
		for column := range resolution {
			receiver := [3]float32{
				((float32(column)+.5)/resolution*2 - 1) * courtyard.HalfWidth,
				0,
				((float32(row)+.5)/resolution*2 - 1) * courtyard.HalfDepth,
			}

			var direct float64

			for j := range samples {
				for i := range samples {
					emitter := [3]float32{
						-9.225 + emitterStep*(float32(i)+.5),
						9,
						.775 + emitterStep*(float32(j)+.5),
					}
					if clearRay(receiver, emitter) {
						dx, dz := float64(emitter[0]-receiver[0]), float64(emitter[2]-receiver[2])
						direct += 46 / (dx*dx + dz*dz + 81)
					}
				}
			}

			direct /= samples * samples

			offset := (row*resolution + column) * 4
			for channel, energy := range [3]float64{.037 + direct*.81, .05 + direct*.62, .08 + direct*.41} {
				pixels[offset+channel] = byte(math.Round(255 * min(energy, 1)))
			}

			pixels[offset+3] = 255
		}
	}

	return pixels
}

func clearRay(start, end [3]float32) bool {
	for _, box := range courtyard.Pillars() {
		low := [3]float32{box.X - box.Width/2, 0, box.Z - box.Depth/2}
		high := [3]float32{box.X + box.Width/2, box.Height, box.Z + box.Depth/2}
		entry, exit := float32(0), float32(1)

		for axis := range start {
			delta := end[axis] - start[axis]
			if delta == 0 {
				if start[axis] < low[axis] || start[axis] > high[axis] {
					entry, exit = 1, 0
				}

				continue
			}

			a, b := (low[axis]-start[axis])/delta, (high[axis]-start[axis])/delta
			entry, exit = max(entry, min(a, b)), min(exit, max(a, b))
		}

		if entry <= exit {
			return false
		}
	}

	return true
}
