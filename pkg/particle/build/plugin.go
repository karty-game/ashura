//go:build !js

package build

import (
	"bytes"
	"fmt"
	"maps"
	"path"
	"slices"
	"strings"

	"github.com/karty-game/ashura/pkg/assetbuild"
)

const publisher = "particlr"

type effectsPlugin struct{ spatial map[string]SpatialLayers }

// Effects publishes .prt inputs as a generated assets package using
// Ashura's prepared particle format.
func Effects() assetbuild.Plugin { return effectsPlugin{} }

// Effects3D publishes .prt inputs with offline layer overrides keyed by filename
// stem and Particlr layer ID. Other effects still use the authored planar motion.
func Effects3D(spatial map[string]SpatialLayers) assetbuild.Plugin {
	return effectsPlugin{spatial: spatial}
}

func (effectsPlugin) Name() string { return publisher }

func (plugin effectsPlugin) Plan(plan *assetbuild.Plan) error {
	files, err := effectFiles(plan)
	if err != nil {
		return err
	}

	for _, name := range slices.Sorted(maps.Keys(plugin.spatial)) {
		if _, found := files[name]; !found {
			return fmt.Errorf("unknown spatial effect %q: %w", name, errDocument)
		}
	}

	const slot = "files"

	options := struct {
		Files   map[string]string
		Spatial map[string]SpatialLayers
	}{files, plugin.spatial}

	refs, err := plan.Add(assetbuild.Action{
		ID: publisher, Processor: publisher, Revision: "4", Options: options,
		Outputs: []assetbuild.Slot{{Name: slot, Schema: "karty.files@1"}},
		Run: func(ctx *assetbuild.Context) (assetbuild.Result, error) {
			bundle := assetbuild.Bundle{"assets.go": []byte(catalog)}

			for _, name := range slices.Sorted(maps.Keys(files)) {
				source := files[name]

				data, err := ctx.ReadFile(source)
				if err != nil {
					return nil, err
				}

				var output bytes.Buffer
				if err := Compile3D(&output, bytes.NewReader(data), plugin.spatial[name]); err != nil {
					return nil, fmt.Errorf("%s: %w", source, err)
				}

				bundle[name+".apr"] = output.Bytes()
			}

			encoded, err := assetbuild.EncodeBundle(bundle)

			return assetbuild.Result{slot: encoded}, err
		},
	})
	if err != nil {
		return err
	}

	plan.Publish(refs[0])

	return nil
}

func effectFiles(plan *assetbuild.Plan) (map[string]string, error) {
	files := make(map[string]string)

	for _, pattern := range plan.Input {
		sources, err := plan.Glob(pattern)
		if err != nil {
			return nil, err
		}

		for _, source := range sources {
			if path.Ext(source) != ".prt" {
				continue
			}

			name := strings.TrimSuffix(path.Base(source), ".prt")
			if !validName(name) {
				return nil, fmt.Errorf("effect name %q: %w", name, errDocument)
			}

			if existing := files[name]; existing != "" && existing != source {
				return nil, fmt.Errorf("duplicate effect name %q: %w", name, errDocument)
			}

			files[name] = source
		}
	}

	if len(files) == 0 {
		return nil, fmt.Errorf("no .prt inputs: %w", errDocument)
	}

	return files, nil
}

func validName(name string) bool {
	return name != "" && !strings.ContainsFunc(name, func(character rune) bool {
		return (character < 'a' || character > 'z') && (character < 'A' || character > 'Z') &&
			(character < '0' || character > '9') && character != '-' && character != '_'
	})
}

const catalog = `// Code generated by Ashura's particlr publisher. DO NOT EDIT.

package assets

import (
	"embed"

	"github.com/karty-game/ashura/pkg/particle"
)

//go:embed *.apr
var effects embed.FS

// Load admits the named prepared effect by its source basename.
func Load(name string) (*particle.Effect, error) {
	file, err := effects.Open(name + ".apr")
	if err != nil {
		return nil, err
	}
	defer file.Close()

	return particle.Read(file)
}
`
