//go:build !js

package build

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"io/fs"
	"path"
	"slices"
	"strconv"
	"strings"

	"github.com/karty-game/ashura/pkg/assetbuild"
	"github.com/karty-game/ashura/pkg/texture"
)

type catalogItem struct {
	name                string
	page                int
	x, y, width, height int
	region              bool
}

func catalogCode(set assetbuild.ImageSet, formats ...texture.Format) ([]byte, error) {
	items, err := catalogItems(set)
	if err != nil {
		return nil, err
	}

	if len(formats) == 0 {
		formats = make([]texture.Format, len(set.Images))
	}

	if len(formats) != len(set.Images) {
		return nil, errImages
	}

	var code strings.Builder

	code.WriteString("// Code generated by engine assets build (draw2d/build.Images). DO NOT EDIT.\n\npackage assets\n")

	writeCatalogImports(&code, formats)

	code.WriteString("\n// Catalog owns the prepared image regions. Images on one page share its storage.\ntype Catalog struct {\n")

	for _, item := range items {
		_, _ = fmt.Fprintf(&code, "%s *draw2d.Image\n", item.name)
	}

	code.WriteString("}\n")

	writePageEmbeds(&code, set, formats, "", "imagePage")
	code.WriteString(
		"\n// Load admits each GPU-ready page once and returns all named images. Call once per asset lifetime and share the catalog.\n",
	)
	writeCatalogLoad(&code, "Load", "imagePage", set, formats, items)

	return formatCatalog(&code)
}

func writePageEmbeds(code *strings.Builder, set assetbuild.ImageSet, formats []texture.Format, directory, prefix string) {
	for index, image := range set.Images {
		_, _ = fmt.Fprintf(
			code, "\n//go:embed %s\nvar %s%d []byte\n",
			strconv.Quote(path.Join(directory, pageFilename(image.Name, formats[index]))), prefix, index,
		)
	}
}

func writeCatalogLoad(code *strings.Builder, name, prefix string, set assetbuild.ImageSet, formats []texture.Format, items []catalogItem) {
	_, _ = fmt.Fprintf(code, "func %s() (Catalog,error) {\nvar result Catalog\n", name)

	for index, image := range set.Images {
		writeCatalogPage(code, prefix, index, image, formats[index])
	}

	for _, item := range items {
		if item.region {
			_, _ = fmt.Fprintf(
				code,
				"result.%s,err=page%d.Region(%d,%d,%d,%d)\nif err!=nil { return Catalog{},err }\n",
				item.name,
				item.page,
				item.x,
				item.y,
				item.width,
				item.height,
			)
		} else {
			_, _ = fmt.Fprintf(code, "result.%s=page%d\n", item.name, item.page)
		}
	}

	code.WriteString("return result,nil\n}\n")
}

func formatCatalog(code *strings.Builder) ([]byte, error) {
	result, err := format.Source([]byte(code.String()))
	if err != nil {
		return nil, fmt.Errorf("generate 2D catalog: %w", err)
	}

	return result, nil
}

func writeCatalogImports(code *strings.Builder, formats []texture.Format) {
	if len(formats) == 0 {
		return
	}

	code.WriteString("\nimport (\n_ \"embed\"\n\"github.com/karty-game/ashura/pkg/draw2d\"\n")

	if slices.Contains(formats, texture.BC1) || slices.Contains(formats, texture.BC7) ||
		slices.Contains(formats, texture.ETC2RGB) || slices.Contains(formats, texture.ETC2RGBA) {
		code.WriteString("\"github.com/karty-game/ashura/pkg/texture\"\n")
	}

	code.WriteString(")\n")
}

func writeCatalogPage(code *strings.Builder, prefix string, index int, image assetbuild.Image, format texture.Format) {
	if format == texture.RGBA8 {
		_, _ = fmt.Fprintf(code, "page%d,err:=draw2d.NewImage(%d,%d,%s%d)\n", index, image.Width, image.Height, prefix, index)
	} else {
		_, _ = fmt.Fprintf(
			code,
			"page%d,err:=draw2d.NewPreparedImage(%d,%d,texture.%s,%s%d)\n",
			index, image.Width, image.Height, compressedFormatName(format), prefix, index,
		)
	}

	code.WriteString("if err!=nil { return Catalog{},err }\n")
}

func compressedFormatName(format texture.Format) string {
	switch format {
	case texture.BC1:
		return "BC1"
	case texture.BC7:
		return "BC7"
	case texture.ETC2RGB:
		return "ETC2RGB"
	case texture.ETC2RGBA:
		return "ETC2RGBA"
	case texture.RGBA8, texture.BC6H, texture.ASTC4x4, texture.ASTC6x6:
		panic("invalid admitted sprite format")
	default:
		panic("invalid admitted sprite format")
	}
}

func catalogItems(set assetbuild.ImageSet) ([]catalogItem, error) {
	if _, err := assetbuild.EncodeImageSet(set); err != nil {
		return nil, err
	}

	pages := make(map[string]int, len(set.Images))
	used := make([]bool, len(set.Images))
	names := make(map[string]bool)
	items := make([]catalogItem, 0, len(set.Images)+len(set.Regions))

	for index, image := range set.Images {
		if image.Usage != assetbuild.UsageAlbedo || len(image.Levels) != 1 {
			return nil, fmt.Errorf("2D image %q requires one albedo RGBA8 level: %w", image.Name, errImages)
		}

		pages[image.Name] = index
		if image.Atlas {
			continue
		}

		if err := addCatalogName(names, image.Name); err != nil {
			return nil, err
		}

		items = append(items, catalogItem{name: image.Name, page: index})
		used[index] = true
	}

	for _, region := range set.Regions {
		if !fs.ValidPath(region.Source) || region.Source == "." {
			return nil, fmt.Errorf("2D image region %q has an invalid source identity: %w", region.Name, errImages)
		}

		if err := addCatalogName(names, region.Name); err != nil {
			return nil, err
		}

		items = append(items, catalogItem{
			name: region.Name, page: pages[region.Page], x: region.X, y: region.Y,
			width: region.Width, height: region.Height, region: true,
		})
		used[pages[region.Page]] = true
	}

	for index, referenced := range used {
		if !referenced {
			return nil, fmt.Errorf("2D atlas page %q has no named regions: %w", set.Images[index].Name, errImages)
		}
	}

	slices.SortFunc(items, func(a, b catalogItem) int { return strings.Compare(a.name, b.name) })

	return items, nil
}

func addCatalogName(names map[string]bool, name string) error {
	if !token.IsIdentifier(name) || !ast.IsExported(name) || names[name] {
		return fmt.Errorf("2D image field %q must be unique and exported: %w", name, errImages)
	}

	names[name] = true

	return nil
}
