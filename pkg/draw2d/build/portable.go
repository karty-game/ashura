package build

import (
	"fmt"
	"path"
	"slices"
	"strings"

	"github.com/karty-game/ashura/internal/imagecatalog"
	"github.com/karty-game/ashura/pkg/assetbuild"
	"github.com/karty-game/ashura/pkg/texture"
)

const mobileDirectory = "mobile"

// PortableImages publishes BC and ETC2 catalogs from the same prepared images
// or atlas. The main catalog includes LoadForDevice for use with the enabled
// device's texture support. Optional compression settings apply to both encoders.
func PortableImages(options ...assetbuild.BlockCompressionOptions) assetbuild.Plugin {
	return portableImagesPlugin{options: options}
}

type portableImagesPlugin struct {
	options []assetbuild.BlockCompressionOptions
}

func (portableImagesPlugin) Name() string { return "draw2d-portable-images" }

func (plugin portableImagesPlugin) Plan(plan *assetbuild.Plan) error {
	var compression assetbuild.BlockCompressionOptions

	switch len(plugin.options) {
	case 0:
	case 1:
		compression = plugin.options[0]
	default:
		return fmt.Errorf("draw2d/build.PortableImages accepts one compression record: %w", errImages)
	}

	desktop := ImagesOptions{OpaqueFormat: texture.BC1, AlphaFormat: texture.BC7, Compression: compression}
	if err := validateImagesOptions(desktop); err != nil {
		return err
	}

	inputs, err := imagecatalog.Inputs(plan, "draw2d/build.Images", errImages)
	if err != nil {
		return err
	}

	if err := planImages(plan, inputs, desktop); err != nil {
		return err
	}

	mobile := ImagesOptions{OpaqueFormat: texture.ETC2RGB, AlphaFormat: texture.ETC2RGBA, Compression: compression}

	if err := planMobileImages(plan, inputs, desktop, mobile); err != nil {
		return err
	}

	plan.DescribeImageFields(inputs, "assets.LoadForDevice(app.SupportsTextureFormat)")

	return nil
}

func planMobileImages(plan *assetbuild.Plan, inputs []assetbuild.Ref, desktop, mobile ImagesOptions) error {
	refs, err := plan.Add(assetbuild.Action{
		ID: "draw2d-images/mobile", Processor: pluginName, Revision: "portable-page-catalog@1",
		Options: struct{ Desktop, Mobile ImagesOptions }{desktop, mobile},
		Inputs:  inputs,
		Outputs: []assetbuild.Slot{{Name: filesSlot, Schema: "karty.files@1"}},
		Run: func(ctx *assetbuild.Context) (assetbuild.Result, error) {
			set, err := imagecatalog.Read(ctx, inputs)
			if err != nil {
				return nil, err
			}

			return mobileCatalog(ctx, set, desktop, mobile)
		},
	})
	if err != nil {
		return err
	}

	plan.Publish(refs[0])

	return nil
}

func mobileCatalog(ctx *assetbuild.Context, set assetbuild.ImageSet, desktop, mobile ImagesOptions) (assetbuild.Result, error) {
	mobileFormats := imageFormats(set, mobile)

	files, err := imageCatalog(ctx, set, mobileFormats, mobile.Compression)
	if err != nil {
		return nil, err
	}

	selector, err := portableCatalogCode(set, imageFormats(set, desktop), mobileFormats)
	if err != nil {
		return nil, err
	}

	output := make(assetbuild.Bundle, len(files)+1)
	for name, data := range files {
		output[path.Join(mobileDirectory, name)] = data
	}

	output["portable.go"] = selector

	return catalogResult(output)
}

func portableCatalogCode(set assetbuild.ImageSet, desktop, mobile []texture.Format) ([]byte, error) {
	var code strings.Builder

	code.WriteString("// Code generated by engine assets build (draw2d/build.PortableImages). DO NOT EDIT.\n\npackage assets\n")

	if len(mobile) == 0 {
		code.WriteString(`import "github.com/karty-game/ashura/pkg/texture"

// LoadForDevice returns the empty sprite catalog.
func LoadForDevice(func(texture.Format) bool) (Catalog,error) { return Load() }
`)

		return formatCatalog(&code)
	}

	items, err := catalogItems(set)
	if err != nil {
		return nil, err
	}

	code.WriteString(`
import (
	_ "embed"
	"errors"
	"github.com/karty-game/ashura/pkg/draw2d"
	"github.com/karty-game/ashura/pkg/texture"
)

var errDeviceCatalog = errors.New("draw2d: device cannot load either prepared sprite catalog")
`)
	writePageEmbeds(&code, set, mobile, mobileDirectory, "mobilePage")
	_, _ = fmt.Fprintf(&code, `
// LoadForDevice admits one prepared catalog after device initialization.
// Pass app.SupportsTextureFormat and share the returned catalog for its lifetime.
func LoadForDevice(supports func(texture.Format) bool) (Catalog,error) {
	if supports != nil {
		if %s { return Load() }
		if %s { return loadMobile() }
	}
	return Catalog{},errDeviceCatalog
}

`, formatSupportChecks(desktop), formatSupportChecks(mobile))
	writeCatalogLoad(&code, "loadMobile", "mobilePage", set, mobile, items)

	return formatCatalog(&code)
}

func formatSupportChecks(formats []texture.Format) string {
	var checks []string

	for _, format := range []texture.Format{texture.BC1, texture.BC7, texture.ETC2RGB, texture.ETC2RGBA} {
		if slices.Contains(formats, format) {
			checks = append(checks, "supports(texture."+compressedFormatName(format)+")")
		}
	}

	return strings.Join(checks, " && ")
}
