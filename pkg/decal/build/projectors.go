//go:build !js

package decalbuild

import (
	"fmt"
	"go/format"
	"go/token"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/karty-game/ashura/internal/decaldata"
	"github.com/karty-game/ashura/pkg/assetbuild"
)

// ProjectorOptions describes one authored batch. Name becomes a Go constructor,
// and Atlas names a single prepared image atlas resource before KTX2 encoding.
type ProjectorOptions struct {
	Name, Atlas string
	Marks       []Mark
}

type projectorPlugin struct{ options ProjectorOptions }

// Projectors publishes a GPU-ready chunk batch and its Go catalog constructor.
func Projectors(options ProjectorOptions) assetbuild.Plugin { return projectorPlugin{options: options} }

func (projectorPlugin) Name() string { return "decal-projectors" }

func (plugin projectorPlugin) Plan(plan *assetbuild.Plan) error {
	options := plugin.options

	first, _ := utf8.DecodeRuneInString(options.Name)
	if !token.IsIdentifier(options.Name) || !unicode.IsUpper(first) ||
		len(options.Marks) == 0 || len(options.Marks) > decaldata.MaxBatch {
		return decaldata.ErrBatch
	}

	_, atlas, err := imageReference(plan, options.Atlas)
	if err != nil {
		return err
	}

	refs, err := plan.Add(assetbuild.Action{
		ID: "decal-projectors/" + options.Name, Processor: plugin.Name(), Revision: "gpu-records@1", Options: options,
		Inputs: []assetbuild.Ref{atlas}, Parallel: true,
		Outputs: []assetbuild.Slot{{Name: "bundle", Schema: "decal-batch-bundle@1"}},
		Run: func(ctx *assetbuild.Context) (assetbuild.Result, error) {
			images, err := readImages(ctx, atlas)
			if err != nil {
				return nil, err
			}

			return buildProjectors(options, images)
		},
	})
	if err != nil {
		return err
	}

	plan.Publish(refs[0])

	return nil
}

func buildProjectors(options ProjectorOptions, images assetbuild.ImageSet) (assetbuild.Result, error) {
	if len(images.Images) != 1 || !images.Images[0].Atlas || images.Images[0].Usage != assetbuild.UsageAlbedo {
		return nil, fmt.Errorf("authored decal batch requires a single albedo atlas page: %w", decaldata.ErrBatch)
	}

	regions := make(map[string]assetbuild.AtlasRegion, len(images.Regions))
	for _, region := range images.Regions {
		regions[region.Source] = region
	}

	placements := make([]decaldata.Placement, 0, len(options.Marks))
	for _, mark := range options.Marks {
		region, ok := regions[mark.Image]
		if !ok {
			return nil, fmt.Errorf("missing decal atlas region %q: %w", mark.Image, decaldata.ErrBatch)
		}

		width, height := float32(region.PageWidth), float32(region.PageHeight)
		placements = append(placements, mark.placement(
			[2]float32{float32(region.X) / width, float32(region.Y) / height},
			[2]float32{float32(region.X+region.Width) / width, float32(region.Y+region.Height) / height},
		))
	}

	data, err := decaldata.Encode(placements)
	if err != nil {
		return nil, err
	}

	base := strings.ToLower(options.Name)
	asset := base + ".decal"
	source := fmt.Sprintf(
		"// Code generated by engine assets build. DO NOT EDIT.\npackage decals\n"+
			"import (_ \"embed\"; \"github.com/karty-game/ashura/pkg/decal\")\n"+
			"//go:embed %q\nvar data%s []byte\n"+
			"// %s loads one prepared projector batch.\nfunc %s() (*decal.Prepared,error) {return decal.DecodePrepared(data%s)}\n",
		asset, options.Name, options.Name, options.Name, options.Name,
	)

	code, err := format.Source([]byte(source))
	if err != nil {
		return nil, err
	}

	bundle, err := assetbuild.EncodeBundle(assetbuild.Bundle{"decals/" + asset: data, "decals/" + base + ".go": code})

	return assetbuild.Result{"bundle": bundle}, err
}
