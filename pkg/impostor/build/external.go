//go:build !js

package impostorbuild

import (
	"crypto/sha256"
	"fmt"
	"go/format"

	"github.com/karty-game/ashura/pkg/assetbuild"
)

func cardFiles(name, source string, prepared []byte, profile string) (assetbuild.Bundle, error) {
	file := "impostor_" + name + ".kimp"
	if profile == "" {
		code, err := catalog(name, source, file)

		return assetbuild.Bundle{"impostors/" + file: prepared, "impostors/impostor_" + name + ".go": code}, err
	}

	path := "texture-profiles/" + profile + "/" + file

	code, err := format.Source(fmt.Appendf(nil, `// Code generated by engine assets build (impostor v4). DO NOT EDIT.
package impostors
import "github.com/karty-game/ashura/pkg/scene/resource"
// %s declares the prepared external impostor %q.
func %s() resource.Asset { return resource.Asset{ID:%q, Path:%q, Size:%d, SHA256:%q} }
`, name, source, name, source, path, len(prepared), fmt.Sprintf("%x", sha256.Sum256(prepared))))
	if err != nil {
		return nil, fmt.Errorf("impostor external catalog: %w", err)
	}

	return assetbuild.Bundle{"public/" + path: prepared, "impostors/" + profile + "/impostor_" + name + ".go": code}, nil
}
