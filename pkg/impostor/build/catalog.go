//go:build !js

package impostorbuild

import (
	"fmt"
	"go/format"
	"strconv"
)

func catalog(name, source, prepared string) ([]byte, error) {
	text := fmt.Sprintf(`// Code generated by engine assets build (impostor v4). DO NOT EDIT.

package impostors

import (
 _ "embed"
 "github.com/karty-game/karty-webgpu/pkg/impostor"
)

//go:embed %s
var asset%s []byte

// %s declares the offline-prepared model impostor %s.
func %s() impostor.Asset { return impostor.Prepared(%s, asset%s) }
`, strconv.Quote(prepared), name, name, strconv.Quote(source), name, strconv.Quote(source), name)

	code, err := format.Source([]byte(text))
	if err != nil {
		return nil, fmt.Errorf("impostor catalog: %w", err)
	}

	return code, nil
}
