//go:build !js

package build

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"io/fs"
	"slices"
	"strconv"
	"strings"

	"github.com/karty-game/ashura/pkg/assetbuild"
)

type catalogItem struct {
	name                string
	page                int
	x, y, width, height int
	region              bool
}

func catalogCode(set assetbuild.ImageSet) ([]byte, error) {
	items, err := catalogItems(set)
	if err != nil {
		return nil, err
	}

	var code strings.Builder

	code.WriteString("// Code generated by engine assets build (ui/build.Images). DO NOT EDIT.\n\npackage assets\n")

	if len(set.Images) > 0 {
		code.WriteString("\nimport (\n_ \"embed\"\n\"github.com/karty-game/ashura/pkg/ui\"\n)\n")
	}

	code.WriteString("\n// Catalog owns the prepared image regions. Images on one page share its storage.\ntype Catalog struct {\n")

	for _, item := range items {
		_, _ = fmt.Fprintf(&code, "%s *ui.ImageAsset\n", item.name)
	}

	code.WriteString("}\n")

	for index, image := range set.Images {
		_, _ = fmt.Fprintf(&code, "\n//go:embed %s\nvar imagePage%d []byte\n", strconv.Quote(pageFilename(image.Name)), index)
	}

	code.WriteString(
		"\n// Load admits each GPU-ready page once and returns all named images. Call once per asset lifetime and share the catalog.\nfunc Load() (Catalog,error) {\nvar result Catalog\n",
	)

	for index, image := range set.Images {
		_, _ = fmt.Fprintf(
			&code,
			"page%d,err:=ui.NewImageAsset(%d,%d,imagePage%d)\nif err!=nil { return Catalog{},err }\n",
			index,
			image.Width,
			image.Height,
			index,
		)
	}

	for _, item := range items {
		if item.region {
			_, _ = fmt.Fprintf(
				&code,
				"result.%s,err=page%d.Region(ui.Rect{X:%d,Y:%d,W:%d,H:%d})\nif err!=nil { return Catalog{},err }\n",
				item.name,
				item.page,
				item.x,
				item.y,
				item.width,
				item.height,
			)
		} else {
			_, _ = fmt.Fprintf(&code, "result.%s=page%d\n", item.name, item.page)
		}
	}

	code.WriteString("return result,nil\n}\n")

	result, err := format.Source([]byte(code.String()))
	if err != nil {
		return nil, fmt.Errorf("generate UI catalog: %w", err)
	}

	return result, nil
}

func catalogItems(set assetbuild.ImageSet) ([]catalogItem, error) {
	if _, err := assetbuild.EncodeImageSet(set); err != nil {
		return nil, err
	}

	pages := make(map[string]int, len(set.Images))
	used := make([]bool, len(set.Images))
	names := make(map[string]bool)
	items := make([]catalogItem, 0, len(set.Images)+len(set.Regions))

	for index, image := range set.Images {
		if image.Usage != assetbuild.UsageAlbedo || len(image.Levels) != 1 {
			return nil, fmt.Errorf("UI image %q requires one albedo RGBA8 level: %w", image.Name, errImages)
		}

		pages[image.Name] = index
		if image.Atlas {
			continue
		}

		if err := addCatalogName(names, image.Name); err != nil {
			return nil, err
		}

		items = append(items, catalogItem{name: image.Name, page: index})
		used[index] = true
	}

	for _, region := range set.Regions {
		if !fs.ValidPath(region.Source) || region.Source == "." {
			return nil, fmt.Errorf("UI image region %q has an invalid source identity: %w", region.Name, errImages)
		}

		if err := addCatalogName(names, region.Name); err != nil {
			return nil, err
		}

		items = append(items, catalogItem{
			name: region.Name, page: pages[region.Page], x: region.X, y: region.Y,
			width: region.Width, height: region.Height, region: true,
		})
		used[pages[region.Page]] = true
	}

	for index, referenced := range used {
		if !referenced {
			return nil, fmt.Errorf("UI atlas page %q has no named regions: %w", set.Images[index].Name, errImages)
		}
	}

	slices.SortFunc(items, func(a, b catalogItem) int { return strings.Compare(a.name, b.name) })

	return items, nil
}

func addCatalogName(names map[string]bool, name string) error {
	if !token.IsIdentifier(name) || !ast.IsExported(name) || names[name] {
		return fmt.Errorf("UI image field %q must be unique and exported: %w", name, errImages)
	}

	names[name] = true

	return nil
}
