//go:build !js

package scenebuild

import (
	"fmt"
	"go/parser"
	"strconv"
	"strings"
)

const factoryTemplate = `
// New%s starts one logical root. setup runs once; mesh residency does not re-run it.
func New%s(id string, services %sServices, setup func(*%s) (func(), error)) (_ *%s, err error) {
 root, err := scene.NewRoot(id)
 if err != nil { return nil, err }
 result := &%s{Root: root}
 committed := false
 defer func() { if !committed { root.Abort() } }()
 %s
 if setup != nil {
   cleanup, setupErr := setup(result)
   if cleanup != nil { if ownErr := root.Own(cleanup); ownErr != nil { cleanup(); return nil, ownErr } }
   if setupErr != nil { return nil, setupErr }
 }
 committed = true
 return result, nil
}
`

func (build *compiler) generate(source, packageName, name string) (string, error) {
	imports := map[string]string{"scene": "github.com/karty-game/karty-webgpu/pkg/scene", "fmt": "fmt"}
	services := make(map[string]string)

	var declarations, factories strings.Builder

	for _, value := range build.ordered {
		if err := mergeNames(imports, value.module.Imports); err != nil {
			return "", err
		}

		if err := mergeNames(services, value.module.Services); err != nil {
			return "", err
		}

		component := &Component{Config: value.node.components[value.module.Name], Path: value.node.path,
			SaveID: value.node.saveID, Root: "result.Root", Ancestors: value.node.ancestors, compiler: build, entry: value}

		expression, err := value.module.Generate(component)
		if err != nil {
			return "", fmt.Errorf("%s node %s component %s: %w", value.node.source, value.node.path, value.module.Name, err)
		}

		if _, err := parser.ParseExpr(expression); err != nil {
			return "", fmt.Errorf("module %s factory expression: %w", value.module.Name, err)
		}

		fmt.Fprintf(&declarations, "%s %s\n", value.field, value.module.GoType)
		fmt.Fprintf(&factories, "result.%s, err = %s\nif err != nil { return nil, fmt.Errorf(%s, err) }\n",
			value.field, expression, strconv.Quote(value.node.path+" "+value.module.Name+": %w"))
	}

	var code strings.Builder
	fmt.Fprintf(&code, "// Code generated by Ashura scene compiler from %s. DO NOT EDIT.\n\npackage %s\n\nimport (\n", source, packageName)

	if len(build.ordered) == 0 {
		delete(imports, "fmt")
	}

	for _, alias := range sortedKeys(imports) {
		fmt.Fprintf(&code, "%s %s\n", alias, strconv.Quote(imports[alias]))
	}

	fmt.Fprintf(
		&code,
		")\n\n// %s contains root-owned typed component references.\ntype %s struct {\nRoot *scene.Root\n%s}\n",
		name,
		name,
		declarations.String(),
	)
	fmt.Fprintf(&code, "\n// %sServices supplies application-owned dependencies.\ntype %sServices struct {\n", name, name)

	for _, service := range sortedKeys(services) {
		fmt.Fprintf(&code, "%s %s\n", service, services[service])
	}

	code.WriteString("}\n")
	fmt.Fprintf(&code, factoryTemplate, name, name, name, name, name, name, factories.String())

	return code.String(), nil
}

func mergeNames(target, extra map[string]string) error {
	for key, value := range extra {
		if !validPackage(key) || value == "" {
			return ErrInvalid
		}

		if previous, found := target[key]; found && previous != value {
			return fmt.Errorf("conflicting generated name %s: %w", key, ErrInvalid)
		}

		target[key] = value
	}

	return nil
}
