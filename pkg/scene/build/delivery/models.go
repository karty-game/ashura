//go:build !js

// Package deliverybuild publishes prepared models as external payloads and typed descriptors.
package deliverybuild

import (
	"crypto/sha256"
	"fmt"
	"go/format"
	"strings"

	"github.com/karty-game/karty-webgpu/pkg/assetbuild"
	modelbuild "github.com/karty-game/karty-webgpu/pkg/model/build"
)

type models struct{}

// Models consumes prepared model resources without embedding their bytes in the game.
// Prior producers should publish only prepared slots if external-only delivery is desired.
func Models() assetbuild.Plugin { return models{} }

func (models) Name() string { return "scene-model-delivery" }

func (models) Plan(plan *assetbuild.Plan) error {
	for _, resource := range plan.Resources {
		schema, err := plan.SlotSchema(resource.Ref)
		if err != nil {
			return err
		}

		if schema != modelbuild.PreparedSchema {
			continue
		}

		refs, err := plan.Add(
			assetbuild.Action{ID: "delivery/" + resource.ID, Processor: "scene-model-delivery", Revision: "external-model@1",
				Options: resource.ID, Inputs: []assetbuild.Ref{resource.Ref},
				Outputs: []assetbuild.Slot{{Name: "files", Schema: "karty.files@1"}},
				Run: func(ctx *assetbuild.Context) (assetbuild.Result, error) {
					data, err := ctx.Input(resource.Ref)
					if err != nil {
						return nil, err
					}

					name := assetbuild.AssetName(strings.TrimSuffix(resource.ID, ".glb"))
					digest := fmt.Sprintf("%x", sha256.Sum256(data))
					file := "models/" + digest + ".kmodel"

					code, err := format.Source(fmt.Appendf(nil, `// Code generated by Ashura external model delivery. DO NOT EDIT.
package assets
import "github.com/karty-game/karty-webgpu/pkg/scene/resource"
func %s() resource.Asset { return resource.Asset{ID:%q,Path:%q,Size:%d,SHA256:%q} }
`, name, resource.ID, file, len(data), digest))
					if err != nil {
						return nil, err
					}

					files, err := assetbuild.EncodeBundle(assetbuild.Bundle{"assets/" + name + ".go": code, "public/" + file: data})

					return assetbuild.Result{"files": files}, err
				}},
		)
		if err != nil {
			return err
		}

		plan.Publish(refs[0])
	}

	return nil
}
