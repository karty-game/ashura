//go:build !js

// Package modelbuild adds offline static GLB preparation to asset recipes.
// It must never be imported by a game runtime; use package model there.
package modelbuild

import (
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"path"
	"slices"
	"strconv"
	"strings"

	"github.com/karty-game/ashura/internal/modeldata"
	"github.com/karty-game/ashura/pkg/assetbuild"
)

const bundleSlot = "files"
const glbProcessor = "glb"

const (
	// PreparedSlot exposes the compiled model for later offline processors.
	PreparedSlot = modeldata.PreparedSlot
	// PreparedSchema identifies the GPU-ready static-model container family;
	// its internal version admits opaque V1 and cutout V2 records.
	PreparedSchema = modeldata.PreparedSchema
)

var errCatalog = errors.New("GLB catalog declaration is invalid or collides")

// GLBOptions controls offline embedded-texture preparation. MaxTextureDimension
// caps either dimension before mip generation, preserving aspect and image roles.
// Zero keeps authored resolution; values must be between zero and 4096.
type GLBOptions struct{ MaxTextureDimension int }

type glbPlugin struct {
	options      GLBOptions
	preparedOnly bool
}

// GLBWithOptions prepares static .glb geometry and embedded textures and publishes
// named model.Asset declarations in the generated models package. A zero texture
// cap retains authored resolution. Source files and geometry are never rewritten.
func GLBWithOptions(options GLBOptions) assetbuild.Plugin { return glbPlugin{options: options} }

func (glbPlugin) Name() string { return glbProcessor }

func (plugin glbPlugin) Plan(plan *assetbuild.Plan) error {
	if plugin.options.MaxTextureDimension < 0 || plugin.options.MaxTextureDimension > 4096 {
		return errCatalog
	}

	selected := make(map[string]bool)

	for _, pattern := range plan.Input {
		files, err := plan.Glob(pattern)
		if err != nil {
			return err
		}

		for _, file := range files {
			if strings.EqualFold(path.Ext(file), ".glb") {
				selected[file] = true
			}
		}
	}

	files := make([]string, 0, len(selected))
	for file := range selected {
		files = append(files, file)
	}

	slices.Sort(files)

	names := make(map[string]bool)

	for _, file := range files {
		name := assetbuild.AssetName(strings.TrimSuffix(file, path.Ext(file)))
		if !token.IsIdentifier(name) || names[name] {
			return fmt.Errorf("%s: %w", name, errCatalog)
		}

		names[name] = true

		if plugin.preparedOnly {
			if err := addPreparedModel(plan, file); err != nil {
				return err
			}

			continue
		}

		if err := addModel(plan, file, name, plugin.options); err != nil {
			return err
		}
	}

	return nil
}

func addModel(plan *assetbuild.Plan, source, name string, options GLBOptions) error {
	refs, err := plan.Add(assetbuild.Action{
		Parallel: true,
		ID:       "glb/" + source, Processor: glbProcessor, Revision: "static-model-cutout-catalog@3",
		Options: struct {
			Source, Name string
			Textures     GLBOptions
		}{source, name, options},
		Outputs: []assetbuild.Slot{{Name: bundleSlot, Schema: "static-model-bundle@2"}, {Name: PreparedSlot, Schema: PreparedSchema}},
		Run: func(ctx *assetbuild.Context) (assetbuild.Result, error) {
			return compileModelAction(ctx, source, name, options)
		},
	})
	if err != nil {
		return err
	}

	plan.Publish(refs[0])

	plan.Resources = append(plan.Resources, assetbuild.Resource{ID: source, Ref: refs[1]})

	return nil
}

func catalog(name, source, prepared string) ([]byte, error) {
	text := fmt.Sprintf(`// Code generated by engine assets build (GLB static model). DO NOT EDIT.

package models

import (
 _ "embed"
 "github.com/karty-game/ashura/pkg/model"
)

//go:embed %s
var asset%s []byte

// %s declares the offline-prepared GLB model %s.
func %s() model.Asset { return model.Prepared(%s, asset%s) }
`, strconv.Quote(prepared), name, name, strconv.Quote(source), name, strconv.Quote(source), name)

	code, err := format.Source([]byte(text))
	if err != nil {
		return nil, fmt.Errorf("model catalog: %w", err)
	}

	return code, nil
}
