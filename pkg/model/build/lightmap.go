const defaultLightmapTimeout = 2 * time.Minute

const (
	// LightmapSlot exposes matching GPU-ready direct-light bake inputs.
	LightmapSlot = "lightmap"
	// LightmapSchema identifies build-prepared chart/BVH/receiver bytes.
	LightmapSchema = "karty.lightmap-inputs@1"
	// RNMLightmapSchema adds material frames and bounce reflectance to scalar inputs.
	RNMLightmapSchema = "karty.lightmap-inputs@2"
	// TransportLightmapSchema adds precomputed diffuse patch transport.
	TransportLightmapSchema = "karty.lightmap-inputs@3"
)

// LightmapOptions selects offline xatlas preparation using the embedded portable
// library. No compiler or tool installation is required.
// Resolution bounds one atlas page (16..2048); zero selects 1024. Padding is
// chart gutter width (1..16); zero selects four texels. Timeout bounds chart
// generation; zero selects two minutes.
type LightmapOptions struct {
	Resolution, Padding uint32
	// RNM prepares UV0 tangent frames and mean linear reflectance for directional GI baking.
	RNM bool
	// PrecomputeTransport prepares static visibility and patch transfer weights offline. Requires RNM.
	PrecomputeTransport bool
	// TransportSamples selects deterministic integration samples (16..128); zero selects 64.
	TransportSamples uint32
	Timeout          time.Duration
}

// LightmappedGLB prepares GLB geometry plus unique UV1, BVH and texel receivers.
// Each source is one complete bake scene and must fit in one atlas page.
func LightmappedGLB(options LightmapOptions) assetbuild.Plugin {
	if options.Resolution == 0 {
		options.Resolution = 1024
	}

	if options.Padding == 0 {
		options.Padding = 4
	}

	if options.TransportSamples == 0 {
		options.TransportSamples = 64
	}

	if options.Timeout == 0 {
		options.Timeout = defaultLightmapTimeout
	}

	return glbPlugin{lightmap: &options}
}

var errLightmapOptions = errors.New("invalid GLB lightmap options")

func validateLightmapOptions(o LightmapOptions) error {
	if o.Resolution < 16 || o.Resolution > 2048 || o.Padding < 1 || o.Padding > 16 || o.Timeout <= 0 || o.Timeout > 10*time.Minute ||
		o.PrecomputeTransport && !o.RNM || o.TransportSamples < 16 || o.TransportSamples > 128 {
		return errLightmapOptions
	}

	return nil
}
func prepareLightmap(ctx *assetbuild.Context, data []byte, options LightmapOptions) (lightmapbuild.Result, error) {
	bakeContext, cancel := context.WithTimeout(ctx.Context, options.Timeout)
	defer cancel()

	return lightmapbuild.Prepare(
		bakeContext,
		data,
		lightmapbuild.Options{
			Resolution:          options.Resolution,
			Padding:             options.Padding,
			RNM:                 options.RNM,
			PrecomputeTransport: options.PrecomputeTransport,
			TransportSamples:    options.TransportSamples,
		},
	)
}
func lightmapCatalog(name, source, prepared string) ([]byte, error) {
	text := fmt.Sprintf(`// Code generated by engine assets build (lightmap inputs). DO NOT EDIT.
package models
import (
 _ "embed"
 "github.com/karty-game/karty-webgpu/pkg/lightmap"
)
//go:embed %s
var lightmap%s []byte
// %sLightmap declares the build-prepared lightmap inputs for %s.
func %sLightmap() lightmap.Declaration { return lightmap.Prepared(%s, lightmap%s) }
`, strconv.Quote(prepared), name, name, strconv.Quote(source), name, strconv.Quote(source), name)

	code, err := format.Source([]byte(text))
	if err != nil {
		return nil, fmt.Errorf("lightmap catalog: %w", err)
	}

	return code, nil
}
