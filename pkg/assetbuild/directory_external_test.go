func TestCatalogGenerationAndStaleRemoval(t *testing.T) {
	t.Parallel()

	root := t.TempDir()

	source, output := filepath.Join(root, "assets"), filepath.Join(root, "generated", "assets")
	if err := os.Mkdir(source, 0o750); err != nil {
		t.Fatal(err)
	}

	catalogImage(t, filepath.Join(source, "brick-normal.png"), false)
	catalogImage(t, filepath.Join(source, "photo.jpg"), true)
	catalogImage(t, filepath.Join(source, "brick-ssbump.png"), false)

	result, err := assetbuild.BuildDirectory(t.Context(), source, output, assetbuild.Options{})
	if err != nil {
		t.Fatal(err)
	}

	const expectedAssets = 3

	count := 0

	for _, action := range result.Actions {
		if action.Processor == "images" {
			count++
		}
	}

	if count != expectedAssets {
		t.Fatalf("asset count=%d", count)
	}

	code := readCatalogFile(t, filepath.Join(output, "assets.go"))
	for _, snippet := range []string{"Code generated by engine assets build.", "func BrickNormal()", "ktx2.Normal(\"brick-normal.png\"", "func Photo()", "func BrickSSBump()", "ktx2.SSBump(\"brick-ssbump.png\""} {
		if !bytes.Contains(code, []byte(snippet)) {
			t.Fatalf("missing declaration %s", snippet)
		}
	}

	if _, err := parser.ParseFile(token.NewFileSet(), "assets.go", code, parser.AllErrors); err != nil {
		t.Fatal(err)
	}

	if err := os.Remove(filepath.Join(source, "photo.jpg")); err != nil {
		t.Fatal(err)
	}

	if _, err := assetbuild.BuildDirectory(t.Context(), source, output, assetbuild.Options{}); err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(filepath.Join(output, "photo.ktx2")); !os.IsNotExist(err) {
		t.Fatalf("stale output survived: %v", err)
	}

	if bytes.Contains(readCatalogFile(t, filepath.Join(output, "assets.go")), []byte("func Photo()")) {
		t.Fatal("stale declaration survived")
	}

	if _, err := os.Stat(filepath.Join(source, "brick-normal.ktx2")); !os.IsNotExist(err) {
		t.Fatal("generated payload was written among source assets")
	}
}

func TestCatalogRejectsCollisionsAndUnownedOutput(t *testing.T) {
	t.Parallel()

	root := t.TempDir()

	source, output := filepath.Join(root, "assets"), filepath.Join(root, "generated")
	if err := os.Mkdir(source, 0o750); err != nil {
		t.Fatal(err)
	}

	catalogImage(t, filepath.Join(source, "photo.png"), false)
	catalogImage(t, filepath.Join(source, "photo.jpg"), true)

	if _, err := assetbuild.BuildDirectory(t.Context(), source, output, assetbuild.Options{}); err == nil {
		t.Fatal("accepted colliding generated names")
	}

	if err := os.Remove(filepath.Join(source, "photo.jpg")); err != nil {
		t.Fatal(err)
	}

	// A failed recipe can still leave its disposable generated/cache build state.
	if err := os.MkdirAll(output, 0o750); err != nil {
		t.Fatal(err)
	}

	keep := filepath.Join(output, "keep.txt")
	if err := os.WriteFile(keep, []byte("user content"), 0o600); err != nil {
		t.Fatal(err)
	}

	if _, err := assetbuild.BuildDirectory(t.Context(), source, output, assetbuild.Options{}); err == nil {
		t.Fatal("accepted an unowned output directory")
	}

	if string(readCatalogFile(t, keep)) != "user content" {
		t.Fatal("modified unrelated output files")
	}

	if _, err := assetbuild.BuildDirectory(t.Context(), source, source, assetbuild.Options{}); err == nil {
		t.Fatal("accepted output among source files")
	}
}

func catalogImage(t *testing.T, path string, jpg bool) {
	t.Helper()

	source := image.NewNRGBA(image.Rect(0, 0, 1, 1))
	source.SetNRGBA(0, 0, color.NRGBA{R: 128, G: 128, B: 255, A: 255})
	//nolint:gosec // The fixture path is confined to t.TempDir.
	file, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = file.Close() }()

	if jpg {
		err = jpeg.Encode(file, source, nil)
	} else {
		err = png.Encode(file, source)
	}

	if err != nil {
		t.Fatal(err)
	}
}

func readCatalogFile(t *testing.T, path string) []byte {
	t.Helper()
	//nolint:gosec // Tests supply only paths beneath t.TempDir.
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}

	return data
}
