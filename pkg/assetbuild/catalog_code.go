//go:build !js

package assetbuild

import (
	"crypto/sha256"
	"fmt"
	"go/format"
	"go/token"
	"strconv"
	"strings"
)

func catalogCode(set PreparedSet) ([]byte, error) {
	var code strings.Builder
	code.WriteString("// Code generated by engine assets build. DO NOT EDIT.\n\npackage assets\n")

	if len(set.Images) > 0 {
		code.WriteString("\nimport (\n_ \"embed\"\n\"github.com/karty-game/ashura/pkg/texture/ktx2\"\n)\n")
	}

	names, outputs := make(map[string]bool), make(map[string]bool)
	if len(set.Regions) > 0 {
		names["AtlasRegion"] = true
	}

	for _, entry := range set.Images {
		if !token.IsIdentifier(entry.Name) || !validUsage(entry.Usage) || names[entry.Name] || outputs[entry.Output] {
			return nil, fmt.Errorf("catalog declaration %q collides or is invalid: %w", entry.Name, errImageRecord)
		}

		names[entry.Name], outputs[entry.Output] = true, true
		identifier := fmt.Sprintf("asset%x", sha256.Sum256([]byte(entry.Name)))
		_, _ = fmt.Fprintf(
			&code,
			"\n//go:embed %s\nvar %s []byte\n\n// %s references %s (%s).\nfunc %s() ktx2.Asset { return ktx2.%s(%s,%s) }\n",
			strconv.Quote(entry.Output),
			identifier,
			entry.Name,
			strconv.Quote(entry.Source),
			entry.Usage,
			entry.Name,
			usageConstructor(entry.Usage),
			strconv.Quote(entry.Source),
			identifier,
		)
	}

	if err := writeCatalogRegions(&code, set.Regions, names); err != nil {
		return nil, err
	}

	result, err := format.Source([]byte(code.String()))
	if err != nil {
		return nil, fmt.Errorf("generate asset catalog: %w", err)
	}

	return result, nil
}

func writeCatalogRegions(code *strings.Builder, regions []AtlasRegion, names map[string]bool) error {
	if len(regions) > 0 {
		code.WriteString(
			"\n// AtlasRegion describes a prepared page and original image bounds. Apply its UV mapping offline.\ntype AtlasRegion struct {\nPage string\nAsset ktx2.Asset\nX,Y,Width,Height,PageWidth,PageHeight int\nUVMin,UVMax [2]float32\n}\n",
		)
	}

	for _, region := range regions {
		name := region.Name + "Region"
		if !names[region.Page] || names[name] || !token.IsIdentifier(name) || region.PageWidth < 1 || region.PageHeight < 1 {
			return fmt.Errorf("catalog region %q is invalid: %w", name, errImageRecord)
		}

		names[name] = true
		_, _ = fmt.Fprintf(
			code,
			"\n// %s references the prepared atlas region for %s.\nfunc %s() AtlasRegion { return AtlasRegion{Page:%s,Asset:%s(),X:%d,Y:%d,Width:%d,Height:%d,PageWidth:%d,PageHeight:%d,UVMin:[2]float32{%.9g,%.9g},UVMax:[2]float32{%.9g,%.9g}} }\n",
			name,
			strconv.Quote(region.Source),
			name,
			strconv.Quote(region.Page),
			region.Page,
			region.X,
			region.Y,
			region.Width,
			region.Height,
			region.PageWidth,
			region.PageHeight,
			float64(region.X)/float64(region.PageWidth),
			float64(region.Y)/float64(region.PageHeight),
			float64(region.X+region.Width)/float64(region.PageWidth),
			float64(region.Y+region.Height)/float64(region.PageHeight),
		)
	}

	return nil
}

func usageConstructor(usage string) string {
	switch usage {
	case UsageNormal:
		return "Normal"
	case UsageAO:
		return "AmbientOcclusion"
	case UsageSSBump:
		return "SSBump"
	case UsageLightmap:
		return "Lightmap"
	case UsageReflection:
		return "Reflection"
	default:
		return "Albedo"
	}
}
