const bundleSlot = "files"

func meshAction(
	name, actionID string,
	options any,
	inputs []assetbuild.Ref,
	read func(*assetbuild.Context) ([]collision.Triangle, error),
) assetbuild.Action {
	return assetbuild.Action{
		ID: actionID, Processor: "static-collision", Revision: "go-bvh@1", Options: options, Inputs: inputs,
		Parallel: true, Outputs: []assetbuild.Slot{{Name: bundleSlot, Schema: "static-collision-go-bundle@1"}},
		Run: func(ctx *assetbuild.Context) (assetbuild.Result, error) {
			triangles, err := read(ctx)
			if err != nil {
				return nil, err
			}

			data, err := prepare(triangles)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}

			code, err := catalog(name, data)
			if err != nil {
				return nil, err
			}

			bundle, err := assetbuild.EncodeBundle(assetbuild.Bundle{path.Join("colliders", "mesh_"+name+".go"): code})
			if err != nil {
				return nil, err
			}

			return assetbuild.Result{bundleSlot: bundle}, nil
		},
	}
}

func publish(plan *assetbuild.Plan, name string, action assetbuild.Action) error {
	first, _ := utf8.DecodeRuneInString(name)
	if !token.IsIdentifier(name) || !unicode.IsUpper(first) {
		return fmt.Errorf("collision catalog name %q must be an exported Go identifier: %w", name, errGeometry)
	}

	refs, err := plan.Add(action)
	if err != nil {
		return err
	}

	plan.Publish(refs[0])

	return nil
}

func catalog(name string, data tree) ([]byte, error) {
	var code bytes.Buffer
	code.WriteString(`// Code generated by engine assets build (static collision). DO NOT EDIT.

package colliders

import (
 "github.com/karty-game/ashura/pkg/collision"
 "github.com/karty-game/ashura/pkg/engine"
)

`)

	_, _ = fmt.Fprintf(&code, "var mesh%s = collision.PreparedMeshV1([]collision.NodeV1{\n", name)
	for _, node := range data.nodes {
		_, _ = fmt.Fprintf(&code, "{Bounds:collision.Bounds{Min:%s,Max:%s},Skip:%d,First:%d,Count:%d},\n",
			vectorSource(node.Bounds.Min), vectorSource(node.Bounds.Max), node.Skip, node.First, node.Count)
	}

	code.WriteString("}, []collision.Triangle{\n")

	for _, triangle := range data.triangles {
		_, _ = fmt.Fprintf(&code, "{A:%s,B:%s,C:%s},\n", vectorSource(triangle.A), vectorSource(triangle.B), vectorSource(triangle.C))
	}

	_, _ = fmt.Fprintf(
		&code,
		"})\n\n// %s returns an immutable static collider.\nfunc %s() *collision.Mesh { return mesh%s }\n",
		name,
		name,
		name,
	)

	return format.Source(code.Bytes())
}

func vectorSource(value engine.Vector3) string {
	var source strings.Builder
	source.WriteString("engine.Vector3{X:")
	source.WriteString(strconv.FormatFloat(float64(value.X), 'g', -1, 32))
	source.WriteString(",Y:")
	source.WriteString(strconv.FormatFloat(float64(value.Y), 'g', -1, 32))
	source.WriteString(",Z:")
	source.WriteString(strconv.FormatFloat(float64(value.Z), 'g', -1, 32))
	source.WriteByte('}')

	return source.String()
}
