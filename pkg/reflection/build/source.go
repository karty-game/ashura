package reflectionbuild

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"io"
	"math"
	"strings"

	"github.com/karty-game/ashura/pkg/assetbuild"
	"github.com/karty-game/ashura/pkg/reflection/scene"
)

const (
	chunkSize       = 32
	chunkOrigin     = -16
	reflectionRange = 32
	maxSourceBytes  = 1 << 20
	maxChunks       = 256
	maxObjects      = 4096
	maxCoordinate   = 65536
)

var errSource = errors.New("invalid reflection room source")

type settings struct {
	reflectionscene.Scene

	Space string `json:"space"`
}

type chunk struct {
	Space   string                   `json:"space"`
	Cell    [3]int                   `json:"cell"`
	Objects []reflectionscene.Object `json:"objects"`
}

// loadSource snapshots the cheap authored records during planning. Only the
// neighborhood enters the probe action options; the runtime scene keeps all
// chunks in this space. File edits never change the recipe executable identity.
func loadSource(plan *assetbuild.Plan, options SceneOptions) (authored, neighborhood reflectionscene.Scene, err error) {
	var source settings
	if err = readSource(plan, options.Source, &source); err != nil {
		return authored, neighborhood, err
	}

	if err = validateSettings(source); err != nil {
		return authored, neighborhood, err
	}

	paths, err := plan.Glob(options.Chunks)
	if err != nil {
		return authored, neighborhood, err
	}

	if len(paths) == 0 || len(paths) > maxChunks {
		return authored, neighborhood, errSource
	}

	authored, neighborhood = source.Scene, source.Scene
	cell := probeCell(source.ProbePosition)
	owners := make(map[string]bool)
	names := make(map[string]bool)
	count := 0

	for _, path := range paths {
		var part chunk
		if err = readSource(plan, path, &part); err != nil {
			return authored, neighborhood, err
		}

		count += len(part.Objects)
		if err = validateChunk(part, owners, names, count); err != nil {
			return authored, neighborhood, fmt.Errorf("%s: %w", path, err)
		}

		if part.Space != source.Space {
			continue
		}

		authored.Objects = append(authored.Objects, part.Objects...)
		if neighbor(cell, part.Cell) {
			neighborhood.Objects = append(neighborhood.Objects, part.Objects...)
		}
	}

	return authored, neighborhood, nil
}

func readSource(plan *assetbuild.Plan, path string, value any) error {
	data, err := plan.ReadFile(path)
	if err != nil {
		return err
	}

	if len(data) > maxSourceBytes {
		return errSource
	}

	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()

	if err := decoder.Decode(value); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}

	var extra any
	if err := decoder.Decode(&extra); !errors.Is(err, io.EOF) {
		return errSource
	}

	return nil
}

func probeCell(position reflectionscene.Vector3) [3]int {
	return [3]int{
		int(math.Floor((float64(position.X) - chunkOrigin) / chunkSize)),
		int(math.Floor((float64(position.Y) - chunkOrigin) / chunkSize)),
		int(math.Floor((float64(position.Z) - chunkOrigin) / chunkSize)),
	}
}

func neighbor(left, right [3]int) bool {
	for axis, value := range left {
		if right[axis] < value-1 || right[axis] > value+1 {
			return false
		}
	}

	return true
}

func planRuntimeScene(plan *assetbuild.Plan, authored reflectionscene.Scene, name string) error {
	refs, err := plan.Add(assetbuild.Action{
		ID: strings.ToLower(name) + "-scene", Processor: "reflection-scene", Revision: "typed-source@1", Options: authored,
		Outputs: []assetbuild.Slot{{Name: "files", Schema: "karty.files@1"}},
		Run: func(*assetbuild.Context) (assetbuild.Result, error) {
			code := fmt.Sprintf("// Code generated by reflectionbuild.Scene. DO NOT EDIT.\n\n"+
				"package assets\n\nimport %q\n\nfunc %sScene() reflectionscene.Scene { return %#v }\n",
				"github.com/karty-game/ashura/pkg/reflection/scene", name, authored)

			data, err := format.Source([]byte(code))
			if err != nil {
				return nil, err
			}

			bundle, err := assetbuild.EncodeBundle(assetbuild.Bundle{strings.ToLower(name) + ".go": data})

			return assetbuild.Result{"files": bundle}, err
		},
	})
	if err != nil {
		return err
	}

	plan.Publish(refs[0])

	return nil
}
